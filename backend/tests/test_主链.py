from app.services import 装载, 结栏, 贯验, 目录, 校验, 夹具


def test_入栏成汇总():
    报告 = 装载.装一批(夹具.读取("入栏成汇总样例"))
    assert 报告["入栏"] == 3
    结 = 结栏.结当前栏()
    assert 结["汇总数"] == 2
    assert 贯验.跑一次()["是否对齐"] is True


def test_坏点进匣():
    报告 = 装载.装一批(夹具.读取("坏点样例"))
    assert 报告["坏点"] == 1
    assert 目录.坏点列表()


def test_门槛拒越界():
    ok, _ = 校验.过门槛(120.0, 目录.栏规(), "PM25")
    assert ok is False


def test_幂等驳回():
    体 = {
        "报文": [{
            "报文编号": "dup-1",
            "站点键": "站-河东",
            "指标键": "PM25",
            "读数": 20,
            "观测时": "2026-11-24T08:01:00Z",
        }]
    }
    assert 装载.装一批(体)["入栏"] == 1
    assert 装载.装一批(体)["驳回"] == 1
